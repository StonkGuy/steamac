#!/usr/bin/env python3
"""Generate wmtr_calls.inc: X(index, name, params_type, class) for the winemetal unix calls of DXMT 4ddb20e or of
Mullion (a DXMT fork with Direct3D 12 whose table keeps DXMT's first 146 calls in the same order and appends its own).
class: A = async (no outputs), S = sync, B = sync and may block (host runs it on a helper thread),
C = sync and heavy (shader/pipeline compile; host runs it on a worker pool).

Usage (reproduces src/wmtr_calls.inc byte-for-byte from a DXMT tree at the pinned revision):

  D=<dxmt>/src/winemetal
  python3 gen/gen_table.py gen/scan_thunks.py \\
      $D/winemetal_thunks.c $D/airconv_thunks.c $D/unix/winemetal_unix.c src/wmtr_calls.inc [source label]

Calls named by an enum value instead of a number (Mullion's WMTUnix* calls) are resolved through the enum in
winemetal.h next to the thunks. The classes of the 146 calls both tables share are by index; later calls by name.
"""
import re, subprocess, sys
out = subprocess.run([sys.executable, '-I', sys.argv[1], sys.argv[2], sys.argv[3]], capture_output=True, text=True).stdout
airconv_idx = {}  # airconv codes are enum names; resolve from the unix table order
table = [l.strip().rstrip(',') for l in open(sys.argv[4]).read().split('__wine_unix_call_funcs[] = {')[1].split('};')[0].split('\n')]
table = [t.lstrip('&') for t in table if t and not t.startswith('//')]
assert len(table) in (146, 147, 174), len(table)  # 147: StonkGuy/dxmt vr-export (WMTVRSubmit); 174: Mullion v0.4
# enum-named unix calls (`enum { WMTUnixA = base, WMTUnixB, ... }` in winemetal.h)
enum_idx = {}
hdr = open(sys.argv[2].rsplit('/', 1)[0] + '/winemetal.h').read() if '/' in sys.argv[2] else ''
for body in re.findall(r'enum\s*\w*\s*\{([^}]*WMTUnix[^}]*)\}', hdr):
    nxt = 0
    for e in [x.strip() for x in re.sub(r'//[^\n]*', '', body).split(',') if x.strip()]:
        n, _, v = e.partition('=')
        nxt = int(v.strip(), 0) if v.strip() else nxt
        enum_idx[n.strip()] = nxt; nxt += 1
rows = {}
for line in out.splitlines():
    k, rest = line.split(' ', 1)
    entries = eval(rest)
    name, ptype = entries[0]
    if k.isdigit():
        idx = int(k)
    else:
        fn = {'sm50_initialize':'thunk_SM50Initialize','sm50_destroy':'thunk_SM50Destroy','sm50_compile':'thunk_SM50Compile',
              'sm50_get_compiled_bitcode':'thunk_SM50GetCompiledBitcode','sm50_destroy_bitcode':'thunk_SM50DestroyBitcode',
              'sm50_get_error_message':'thunk_SM50GetErrorMessage','sm50_free_error':'thunk_SM50FreeError',
              'sm50_compile_tessellation_hull':'thunk_SM50CompileTessellationPipelineHull',
              'sm50_compile_tessellation_domain':'thunk_SM50CompileTessellationPipelineDomain',
              'sm50_compile_geometry_pipeline_vertex':'thunk_SM50CompileGeometryPipelineVertex',
              'sm50_compile_geometry_pipeline_geometry':'thunk_SM50CompileGeometryPipelineGeometry',
              'sm50_get_arguments_info':'thunk_SM50GetArgumentsInfo','sm50_get_ray_shader':'thunk_SM50GetRayShader'}.get(k)
        if fn:
            idx = table.index(fn)
        elif k in enum_idx:
            idx = enum_idx[k]
        else:
            continue
        if k == 'sm50_get_arguments_info': name, ptype = 'SM50GetArgumentsInfo', 'sm50_get_arguments_info_params'
    rows[idx] = (name, ptype)
A = {0,1,12,17,33,36,37,38,45,46,47,48,55,58,59,64,65,70,73,86,87,100,102,103,104,107,110,118,133,134,135,136,137}
B = {13,67,109,126}
C = {25,26,29,34,35,98,112,131,144}
# calls after the shared 146, by unix function name
NAMED = {
    '_WMTVRSubmit': 'A',
    # Mullion v0.4: encoding, signalling and statistics without outputs
    '_MTL4CommandQueue_updateMappings': 'A', '_MTL4CommandQueue_copyMappings': 'A', '_MTL4CommandQueue_event': 'A',
    '_MTLAccelerationStructureCommandEncoder_encodeCommands': 'A', '_MTLCommandBuffer_pushDebugGroup': 'A',
    '_MTLCommandBuffer_popDebugGroup': 'A', '_MetalDrawable_countPresent': 'A', '_MTL4CommandEncoder_encodeCommands': 'A',
    '_MTL4CommandEncoder_endEncoding': 'A', '_MTL4CommandBuffer_commit': 'A', '_MTL4CommandBuffer_present': 'A',
    '_MTL4CommandBuffer_waitForEvent': 'A',
    '_MTL4CommandBuffer_waitUntilCompleted': 'B',
    '_MTLDevice_newLinkedComputePipelineState': 'C', 'thunk_SM50GetRayShader': 'C',
}
for i, t in enumerate(table):
    if i >= 146 and t in NAMED:
        {'A': A, 'B': B, 'C': C}[NAMED[t]].add(i)
    if t in ('thunk_SM50Initialize','thunk_SM50Compile','thunk_SM50CompileTessellationPipelineHull',
             'thunk_SM50CompileTessellationPipelineDomain','thunk_SM50CompileGeometryPipelineVertex',
             'thunk_SM50CompileGeometryPipelineGeometry'): C.add(i)
with open(sys.argv[5], 'w') as f:
    label = sys.argv[6] if len(sys.argv) > 6 else 'DXMT 4ddb20e'
    f.write(f'/* generated by gen/gen_table.py from {label} src/winemetal; do not edit */\n')
    for i in range(len(table)):
        if i not in rows:
            f.write(f'X({i}, NULL_{i}, void, N)\n'); continue
        name, ptype = rows[i]
        cls = 'A' if i in A else 'B' if i in B else 'C' if i in C else 'S'
        if ptype.startswith('param:'): ptype = 'obj_handle_t'
        else: ptype = 'struct ' + ptype
        f.write(f'X({i}, {name}, {ptype}, {cls})\n')
print('ok')
