#!/usr/bin/env python3
"""Generate wmtr_cmds.inc from the host encodeCommands switches in winemetal_unix.c:
CMD(kind, enum_value, struct_name) for blit/compute/render, and acceleration structure where the source has it
(Mullion); Nop (no body) maps to wmtcmd_base. Usage: gen_cmds.py <winemetal_unix.c> <out> [source label]"""
import re, sys
src = open(sys.argv[1]).read()
label = sys.argv[3] if len(sys.argv) > 3 else 'DXMT 4ddb20e'
out = [f'/* generated by gen/gen_cmds.py from {label} winemetal_unix.c; do not edit */']
kinds = [('BLIT', '_MTLBlitCommandEncoder_encodeCommands'), ('COMPUTE', '_MTLComputeCommandEncoder_encodeCommands'),
         ('RENDER', '_MTLRenderCommandEncoder_encodeCommands')]
if '\n_MTLAccelerationStructureCommandEncoder_encodeCommands(' in src:
    kinds.append(('ACCEL', '_MTLAccelerationStructureCommandEncoder_encodeCommands'))
for kind, fn in kinds:
    body = src[src.index('\n' + fn + '(') :]
    body = body[: body.index('\n}\n')]
    # a case may start with guards (`if (...) break;`) before its body cast
    cases = re.findall(r'case (\w+):(?:\s*\{)?(?:\s*if \([^;{}]*\)\s*break;)*\s*(?:struct (wmtcmd_\w+) \*body)?', body)
    pending = []
    for enum, st in cases:
        pending.append(enum)
        if st or 'Nop' in enum:
            for e in pending:
                out.append(f'CMD({kind}, {e}, {st or "wmtcmd_base"})')
            pending = []
    assert not pending, (kind, pending)
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(len(out) - 1, 'commands')
