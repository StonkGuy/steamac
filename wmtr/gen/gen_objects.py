#!/usr/bin/env python3
"""Generate object-field metadata from DXMT's public layouts (no guessed word scanning).
Usage: python3 gen/gen_objects.py <dxmt>/src/winemetal > src/wmtr_objects.inc
       python3 gen/gen_objects.py <mullion>/src/winemetal mullion > src/wmtr_objects_mullion.inc
Pointer traversal remains explicit in wmtr_host.m, alongside request relocation decoding.
The Mullion flavour reads src/wmtr_calls_mullion.inc and src/wmtr_cmds_mullion.inc, writes
src/wmtr_object_cmds_mullion.inc, and also lists the pointer fields of Mullion's own calls (146 on):
the executor refuses such a call when a non-null pointer field reached it without a relocation.
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
flavour = sys.argv[2] if len(sys.argv) > 2 else ''
suffix = '_' + flavour if flavour else ''
pointers = {}
structs = {}
for name in ('winemetal.h', 'winemetal_thunks.h'):
    text = (root / name).read_text()
    for typ, body in re.findall(r'struct (\w+)\s*\{(.*?)\n\};', text, re.S):
        fields = []
        for kind, field, count in re.findall(r'\b(obj_handle_t|struct \w+)\s+(\w+)(?:\[(\d+)\])?\s*;', body):
            fields.append((kind, field, int(count or 1)))
        structs[typ] = fields
        # pointer fields declared one or several to a line (`struct WMTConstMemoryPointer directory, lines;`)
        pointers[typ] = [f.strip() for decl in re.findall(r'struct WMT(?:Const)?MemoryPointer\s+([\w\s,]+);', body)
                         for f in decl.split(',')]

def objects(typ, prefix=''):
    result = []
    for kind, field, count in structs.get(typ, []):
        for index in range(count):
            path = prefix + field + (f'[{index}]' if count != 1 else '')
            if kind == 'obj_handle_t':
                result.append(path)
            elif kind[7:] not in ('WMTMemoryPointer', 'WMTConstMemoryPointer'):
                result += objects(kind[7:], path + '.')
    return result

print('/* Generated by gen/gen_objects.py; object fields only, never pointer/scalar words. */')
print('#ifdef WMTR_OBJECT_STRUCTS')
for typ in structs:
    fields = objects(typ)
    if fields or typ.startswith('wmtcmd_'):
        print(f'static int objects_{typ}(struct object_walk *w, struct {typ} *p, int output) {{')
        for field in fields:
            isout = field.startswith('ret')
            if typ == 'unixcall_mtlsharedevent_setevent' and field == 'event_handle':
                continue  # guest Win32 handle, not an ObjC object
            print(f'  if (output == {int(isout)} && !object_field(w, &p->{field})) return 0;')
        print('  return 1;\n}')
print('#endif\n#ifdef WMTR_OBJECT_CALLS')
table = pathlib.Path(__file__).parents[1] / f'src/wmtr_calls{suffix}.inc'
# Display IDs and color-space enums use generic object structs, but are scalars, not ObjC objects.
skip = {0, 1, 10, 92, 94, 95, 96, 114}
# Mullion: calls the executor refuses (host files, bootstrap names) carry no objects worth checking
if flavour == 'mullion':
    skip |= {168, 180, 193, 196}
rows = [(int(call), typ) for call, name, typ in re.findall(r'X\((\d+), (\w+), (.*?), \w\)', table.read_text())]
for call, typ in rows:
    if call in skip:
        continue
    if typ.startswith('struct ') and objects(typ[7:]):
        print(f'case {call}: return objects_{typ[7:]}(w, (void *)payload, output);')
    elif typ == 'obj_handle_t' and flavour:
        # the params are the receiver alone (Mullion's Metal 4 commit and waits), like retain and release
        print(f'case {call}: return output || object_field(w, (obj_handle_t *)payload);')
print('#endif')
if flavour:
    # (call, offset of a pointer field): Mullion's own calls only; the shared ones are DXMT's and checked as DXMT's
    print('#ifdef WMTR_POINTER_FIELDS')
    for call, typ in rows:
        if call >= 146 and typ.startswith('struct ') and call not in skip:
            for field in pointers.get(typ[7:], []):
                print(f'{{{call}, offsetof({typ}, {field})}},')
    print('#endif')
cmds = []
for kind, value, typ in re.findall(r'CMD\((\w+), (\w+), (\w+)\)', (table.parent / f'wmtr_cmds{suffix}.inc').read_text()):
    cmds.append(f'#ifdef WMTR_COMMAND_{kind}\nCMD({kind}, {value}, {typ})\n#endif\n')
(table.parent / f'wmtr_object_cmds{suffix}.inc').write_text('/* Generated by gen/gen_objects.py. */\n' + ''.join(cmds))
