#!/usr/bin/env python3
"""Generate object-field metadata from DXMT's public layouts (no guessed word scanning).
Usage: python3 gen/gen_objects.py <dxmt>/src/winemetal > src/wmtr_objects.inc
Pointer traversal remains explicit in wmtr_host.m, alongside request relocation decoding.
"""
import pathlib
import re
import sys

root = pathlib.Path(sys.argv[1])
structs = {}
for name in ('winemetal.h', 'winemetal_thunks.h'):
    text = (root / name).read_text()
    for typ, body in re.findall(r'struct (\w+)\s*\{(.*?)\n\};', text, re.S):
        fields = []
        for kind, field, count in re.findall(r'\b(obj_handle_t|struct \w+)\s+(\w+)(?:\[(\d+)\])?\s*;', body):
            fields.append((kind, field, int(count or 1)))
        structs[typ] = fields

def objects(typ, prefix=''):
    result = []
    for kind, field, count in structs.get(typ, []):
        for index in range(count):
            path = prefix + field + (f'[{index}]' if count != 1 else '')
            if kind == 'obj_handle_t':
                result.append(path)
            elif kind[7:] not in ('WMTMemoryPointer', 'WMTConstMemoryPointer'):
                result += objects(kind[7:], path + '.')
    return result

print('/* Generated by gen/gen_objects.py; object fields only, never pointer/scalar words. */')
print('#ifdef WMTR_OBJECT_STRUCTS')
for typ in structs:
    fields = objects(typ)
    if fields or typ.startswith('wmtcmd_'):
        print(f'static int objects_{typ}(struct object_walk *w, struct {typ} *p, int output) {{')
        for field in fields:
            isout = field.startswith('ret')
            if typ == 'unixcall_mtlsharedevent_setevent' and field == 'event_handle':
                continue  # guest Win32 handle, not an ObjC object
            print(f'  if (output == {int(isout)} && !object_field(w, &p->{field})) return 0;')
        print('  return 1;\n}')
print('#endif\n#ifdef WMTR_OBJECT_CALLS')
table = pathlib.Path(__file__).parents[1] / 'src/wmtr_calls.inc'
# Display IDs and color-space enums use generic object structs, but are scalars, not ObjC objects.
skip = {0, 1, 10, 92, 94, 95, 96, 114}
for call, name, typ in re.findall(r'X\((\d+), (\w+), (.*?), \w\)', table.read_text()):
    call = int(call)
    if call in skip:
        continue
    if typ.startswith('struct ') and objects(typ[7:]):
        print(f'case {call}: return objects_{typ[7:]}(w, (void *)payload, output);')
print('#endif')
cmds = []
for kind, value, typ in re.findall(r'CMD\((\w+), (\w+), (\w+)\)', (table.parent / 'wmtr_cmds.inc').read_text()):
    cmds.append(f'#ifdef WMTR_COMMAND_{kind}\nCMD({kind}, {value}, {typ})\n#endif\n')
(table.parent / 'wmtr_object_cmds.inc').write_text('/* Generated by gen/gen_objects.py. */\n' + ''.join(cmds))
