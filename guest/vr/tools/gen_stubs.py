"""Generate logging stub classes for every OpenVR interface in openvr.h.

For each `class IVRxxx` the output has `class StubIVRxxx : public vr::IVRxxx` that implements every pure
virtual method: it logs the first call (the runtime's "unknown method" record) and returns a value-initialised
result. The runtime's real classes derive from these stubs and `override` what they implement, so the compiler
checks every signature against the header and nothing is left pure virtual.

Usage: gen_stubs.py openvr.h > stubs.gen.h
"""
import re
import sys


def classes(text):
    for m in re.finditer(r"^\s*class (IVR\w+)\s*\n\s*\{(.*?)\n\s*\};", text, re.S | re.M):
        yield m.group(1), m.group(2)


def methods(body):
    body = re.sub(r"/\*.*?\*/", "", body, flags=re.S)
    body = re.sub(r"//[^\n]*", "", body)
    for m in re.finditer(r"virtual\s+(.*?)\s*=\s*0\s*;", body, re.S):
        decl = " ".join(m.group(1).split())
        dm = re.match(r"(.*?)\b(\w+)\s*\((.*)\)\s*(const)?\s*$", decl)
        if not dm:
            raise SystemExit("cannot parse: " + decl)
        ret, name, args = dm.group(1).strip(), dm.group(2), dm.group(3).strip()
        cq = " const" if dm.group(4) else ""
        # drop default arguments (an override must not need them)
        args = ", ".join(re.sub(r"\s*=\s*[^,]+$", "", a.strip()) for a in split_args(args)) if args else ""
        yield ret, name, args, cq


def split_args(s):
    depth, cur, out = 0, "", []
    for ch in s:
        if ch in "(<":
            depth += 1
        elif ch in ")>":
            depth -= 1
        if ch == "," and depth == 0:
            out.append(cur)
            cur = ""
        else:
            cur += ch
    out.append(cur)
    return out


def main():
    text = open(sys.argv[1], encoding="utf-8").read()
    print("// Generated by tools/gen_stubs.py from openvr.h; do not edit.")
    print("#pragma once")
    print('#include "openvr.h"')
    print('#include "log.h"')
    print("namespace svr {")
    print("using namespace vr;")
    for cls, body in classes(text):
        print(f"class Stub{cls} : public vr::{cls} {{")
        print("public:")
        for ret, name, args, cq in methods(body):
            print(f"  {ret} {name}({args}){cq} override {{")
            print(f'    stub_once("{cls}::{name}");')
            if ret != "void":
                print(f"    return {default_value(ret)};")
            print("  }")
        print("};")
    print("}  // namespace svr")


def default_value(ret):
    # value-initialised result of the declared type, with vr:: types resolved
    t = ret.strip()
    if t.endswith("*"):
        return "nullptr"
    if not t.startswith(("vr::", "uint", "int", "bool", "float", "double", "char")):
        t = "vr::" + t
    return t + "{}"


if __name__ == "__main__":
    main()
