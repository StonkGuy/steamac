#!/usr/bin/env python3
"""Generate d3dr's COM stub bases from the mingw-w64 (widl) headers.

For each interface named on the command line, emits `struct Stub_<I> : <I>` that implements every method of the
interface and of its bases (except IUnknown) as "unimplemented": it logs once and returns E_NOTIMPL / a zero value.
The client's real classes derive from these stubs and override what d3dr implements, so a method the remoting does
not cover yet fails visibly instead of leaving a hole in the vtable.

Usage: gen_stubs.py OUT.h HEADER.h [HEADER.h ...] -- IFACE [IFACE ...]
"""
import re
import sys


def parse(headers):
    ifaces = {}
    block = re.compile(r'MIDL_INTERFACE\("[^"]+"\)\s*\n(\w+)\s*:\s*public\s+(\w+)\s*\n\{(.*?)\n\};', re.S)
    meth = re.compile(r'virtual\s+(.+?)\s+STDMETHODCALLTYPE\s+(\w+)\s*\((.*?)\)\s*=\s*0;', re.S)
    for h in headers:
        text = open(h).read()
        for m in block.finditer(text):
            name, base, body = m.group(1), m.group(2), m.group(3)
            methods = []
            for mm in meth.finditer(body):
                params = ' '.join(mm.group(3).split())
                methods.append((' '.join(mm.group(1).split()), mm.group(2), params))
            ifaces.setdefault(name, (base, methods))
    return ifaces


def chain(ifaces, name):
    out = []
    while name in ifaces and name != 'IUnknown':
        base, methods = ifaces[name]
        out = methods + out
        name = base
    return out


def args_of(params):
    if params in ('', 'void'):
        return ''
    names = []
    for p in params.split(','):
        p = p.strip()
        names.append(re.sub(r'\[.*\]$', '', p).split()[-1].lstrip('*'))
    return ', '.join(names)


def main():
    argv = sys.argv[1:]
    sep = argv.index('--')
    out, headers, names = argv[0], argv[1:sep], argv[sep + 1:]
    ifaces = parse(headers)
    lines = ['/* generated by d3dr/tools/gen_stubs.py from the mingw-w64 headers; do not edit */', '#pragma once', '']
    for n in names:
        if n not in ifaces:
            sys.exit('gen_stubs: interface %s not found' % n)
        lines.append('struct Stub_%s : %s {' % (n, n))
        seen = set()
        for ret, m, params in chain(ifaces, n):
            if m in seen:
                continue
            seen.add(m)
            if ret == 'HRESULT':
                r = 'return E_NOTIMPL;'
            elif ret == 'void':
                r = ''
            else:
                r = 'return %s();' % ret if '*' not in ret else 'return nullptr;'
            lines.append('    %s STDMETHODCALLTYPE %s(%s) { d3dr_unimpl("%s::%s"); %s }' % (ret, m, params, n, m, r))
        lines.append('};')
        lines.append('')
    open(out, 'w').write('\n'.join(lines))


if __name__ == '__main__':
    main()
